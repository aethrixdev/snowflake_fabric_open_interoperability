-- Role/grant setup
-- Run this as ACCOUNTADMIN (or a role with privileges to grant access on integrations/volumes)

-- 1. Create database and warehouse if they do not exist
CREATE DATABASE IF NOT EXISTS ${SNOWFLAKE_DATABASE};
CREATE WAREHOUSE IF NOT EXISTS ${SNOWFLAKE_WAREHOUSE}
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

-- 2. Grant usage privileges on database and warehouse to the target developer role
GRANT USAGE ON DATABASE ${SNOWFLAKE_DATABASE} TO ROLE ${SNOWFLAKE_ROLE};
GRANT CREATE SCHEMA ON DATABASE ${SNOWFLAKE_DATABASE} TO ROLE ${SNOWFLAKE_ROLE};
GRANT USAGE ON SCHEMA ${SNOWFLAKE_DATABASE}.public TO ROLE ${SNOWFLAKE_ROLE};
GRANT CREATE STAGE ON SCHEMA ${SNOWFLAKE_DATABASE}.public TO ROLE ${SNOWFLAKE_ROLE};
GRANT CREATE TABLE ON SCHEMA ${SNOWFLAKE_DATABASE}.public TO ROLE ${SNOWFLAKE_ROLE};
GRANT CREATE ICEBERG TABLE ON SCHEMA ${SNOWFLAKE_DATABASE}.public TO ROLE ${SNOWFLAKE_ROLE};
GRANT USAGE ON WAREHOUSE ${SNOWFLAKE_WAREHOUSE} TO ROLE ${SNOWFLAKE_ROLE};

-- 3. Grant usage privileges on the Storage Integration and External Volume to the target developer role
GRANT USAGE ON INTEGRATION ${SNOWFLAKE_STORAGE_INTEGRATION} TO ROLE ${SNOWFLAKE_ROLE};
GRANT USAGE ON EXTERNAL VOLUME ${SNOWFLAKE_EXTERNAL_VOLUME} TO ROLE ${SNOWFLAKE_ROLE};
